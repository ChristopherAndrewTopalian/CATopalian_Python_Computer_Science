# dictionary_of_dictionaries_show_keys.py

pokemon = {
    "pikachu":
    {
        "name": "Pikachu",
        "type": "Electric",
        "friend": "Ash"
    },

    "charizard":
    {
        "name": "Charizard",
        "type": "Fire",
    },

    "charmander":
    {
        "name": "Charmander",
        "type": "Fire",
    }
}

for key in pokemon:
    print(pokemon[key])

