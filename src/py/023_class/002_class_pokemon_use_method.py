# class_pokemon_use_method.py

class Pokemon:
    def __init__(this, name, kind):
        this.name = name
        this.kind = kind

    def showInfo(this):
        print("Name: " + this.name + "\n" + "Kind: " + this.kind)

pikachu = Pokemon(
"Pikachu",   #name
"Electric"     #kind
)

pikachu.showInfo()

input("Press Enter to Exit")

'''
Name: Pikachu
Kind: Electric
Press Enter to Exit
'''

